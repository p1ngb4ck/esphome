_modules: dict[str, object] | None = None


def _load() -> dict[str, object]:
    global _modules  # noqa: PLW0603 -- loaded once, on first use
    if _modules is None:
        _modules = {}
        for info in pkgutil.iter_modules(__path__):
            # File names follow XKB's, some of which ("in", "is") are Python keywords.
            _modules[info.name] = importlib.import_module(f"{__name__}.{info.name}")
    return _modules


def resolve(name: str) -> tuple[str, dict[int, tuple[str, ...]]]:
    """(description, {usage: characters per level}) of a layout name; KeyError if unknown."""
    m = re.fullmatch(r"\s*([\w-]+)\s*(?:\(\s*([\w-]+)\s*\))?\s*", name)
    if m is None:
        raise KeyError(name)
    module = _load()[m.group(1)]
    variant = m.group(2) or module.DEFAULT
    description, keys = module.LAYOUTS[variant]
    if variant == module.DEFAULT:
        return description, dict(keys)
    full = dict(module.LAYOUTS[module.DEFAULT][1])
    full.update(keys)
    return description, full


def combining(symbol: str) -> str | None:
    """The combining character of a dead key, or None if the symbol is not one."""
    name = DEAD_KEYS.get(symbol)
    return unicodedata.lookup(name) if name is not None else None


def compose_table(keys: dict[int, tuple[str, ...]]) -> list[tuple[str, str, str]]:
    """(combining, base, result) for every dead key of the layout with every character it
    types, and space; only pairs that make one precomposed character, or a spacing form."""
    dead = {
        c for levels in keys.values() for s in levels if (c := combining(s)) is not None
    }
    bases = {
        s
        for levels in keys.values()
        for s in levels
        if len(s) == 1 and combining(s) is None
    }
    out = []
    for mark in sorted(dead):
        spacing = SPACING.get(unicodedata.name(mark))
        if spacing is not None:
            out.append((mark, " ", spacing))
            out.append((mark, mark, spacing))
        for base in sorted(bases):
            composed = unicodedata.normalize("NFC", base + mark)
            if len(composed) == 1 and composed != base:
                out.append((mark, base, composed))
    return out
